# =========================================================
# META WEBHOOK VERIFICATION
# =========================================================

@app.get("/webhook")
async def verify_webhook(request: Request):

    params = request.query_params

    mode = params.get("hub.mode")
    token = params.get("hub.verify_token")
    challenge = params.get("hub.challenge")

    if mode == "subscribe" and token == VERIFY_TOKEN:

        return Response(
            content=challenge,
            media_type="text/plain"
        )

    raise HTTPException(
        status_code=403,
        detail="Verification failed"
    )


# =========================================================
# META WEBHOOK RECEIVE MESSAGE
# =========================================================

@app.post("/webhook")
async def handle_webhook(
    request: Request,
    background_tasks: BackgroundTasks
):

    data = await request.json()

    if data.get("object") == "page":

        for entry in data.get("entry", []):

            for messaging_event in entry.get("messaging", []):

                if (
                    messaging_event.get("message")
                    and not messaging_event["message"].get("is_echo")
                ):

                    sender_id = messaging_event["sender"]["id"]

                    user_text = messaging_event["message"].get(
                        "text",
                        ""
                    )

                    if user_text:

                        print(
                            f"Received message from "
                            f"{sender_id}: {user_text}"
                        )

                        background_tasks.add_task(
                            process_ai_response,
                            sender_id,
                            user_text
                        )

        return Response(
            content="EVENT_RECEIVED",
            status_code=200
        )

    return Response(
        content="NOT_A_PAGE_EVENT",
        status_code=404
    )


